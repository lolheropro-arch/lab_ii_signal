"""
config.py — ค่าตั้งทั้งหมดของโปรแกรมอยู่ที่ไฟล์นี้ไฟล์เดียว
=====================================================================
แก้ค่าที่นี่แล้วรันโปรแกรมใหม่ ไม่ต้องไปแก้ในไฟล์อื่น
"""
import sys
from pathlib import Path

# ---------------------------------------------------------------------
# 1) ตำแหน่งไฟล์
# ---------------------------------------------------------------------
BASE_DIR = Path(__file__).resolve().parent
SONGS_DIR = BASE_DIR / "songs"            # โฟลเดอร์ใส่ไฟล์เพลง (mp3/wav/...)
DB_PATH = BASE_DIR / "fingerprints.db"    # ฐานข้อมูล hash (สร้างให้อัตโนมัติ)
RESULTS_DIR = BASE_DIR / "results"        # ผลการทดลองจาก experiment.py
AUDIO_EXTENSIONS = (".mp3", ".wav", ".flac", ".ogg", ".m4a")

# ---------------------------------------------------------------------
# 2) การรับเสียงจาก ESP32 ผ่าน USB-Serial
#    ต้องตั้งให้ตรงกับ Arduino sketch ที่ส่งข้อมูลมา
# ---------------------------------------------------------------------
# Windows ใช้ "COM3", "COM4", ...   Linux ใช้ "/dev/ttyUSB0" หรือ "/dev/ttyACM0"
# (ใน GUI เลือกพอร์ตใหม่ได้ ค่านี้เป็นแค่ค่าเริ่มต้น)
SERIAL_PORT = "COM3" if sys.platform.startswith("win") else "/dev/ttyUSB0"
BAUD_RATE = 2_000_000
SERIAL_TIMEOUT = 2.0         # วินาที — ถ้าไม่มีข้อมูลเข้านานกว่านี้จะแจ้ง error

INPUT_FS = 16000             # sample rate ที่บอร์ดส่งมา (S/s)
BLOCK_SIZE = 1024            # จำนวน sample ต่อหนึ่งบล็อก
SYNC_BYTES = b"\xAA\x55"     # header หน้าทุกบล็อก (ตั้งเป็น b"" ถ้า sketch ไม่ส่ง header)
SAMPLE_DTYPE = "<i2"         # "<i2" = int16 little-endian (I2S/INMP441)
                             # "<u2" = uint16 little-endian (ADC 12-bit ของ ESP32/MAX10)

# ---------------------------------------------------------------------
# 3) การอัดเสียงเพื่อค้นหา
# ---------------------------------------------------------------------
RECORD_SECONDS = 8           # ความยาวเสียงที่ฟังก่อนค้นหา (วินาที)
DEFAULT_SOURCE = "serial"    # "serial" = ไมค์ผ่าน FPGA + ESP32, "file" = ไฟล์ทดสอบ

# ---------------------------------------------------------------------
# 4) พารามิเตอร์ Fingerprint (หัวใจของอัลกอริทึม)
#    *** ถ้าแก้ค่าในส่วนนี้ ต้อง "ล้างฐานข้อมูล" แล้วเพิ่มเพลงใหม่ ***
# ---------------------------------------------------------------------
FS = 8000                    # ลด sample rate เหลือ 8 kHz ก่อนวิเคราะห์ (ข้อมูลเพลงสำคัญอยู่ < 4 kHz)
NFFT = 1024                  # ขนาด FFT → ความละเอียดความถี่ = FS/NFFT = 7.8 Hz
HOP = 256                    # ระยะเลื่อนเฟรม → 1 เฟรม = HOP/FS = 32 ms
FREQ_MIN = 300               # สนใจเฉพาะ 300–3800 Hz (ลำโพงมือถือแทบไม่มีเบส)
FREQ_MAX = 3800

PEAK_NEIGHBORHOOD = (15, 9)  # ขนาดพื้นที่หา local maximum (ช่องความถี่, เฟรม)
PEAK_MIN_DB = 10             # จุดยอดต้องดังกว่าค่ากลาง (median) ของ spectrogram อย่างน้อยกี่ dB

FAN_OUT = 10                 # จุดยึด 1 จุดจับคู่กับจุดถัดไปได้กี่จุด
TARGET_DT_MIN = 1            # ช่วงเวลาของจุดคู่ (เฟรม)
TARGET_DT_MAX = 63           # 63 เฟรม ≈ 2 วินาที (ต้องไม่เกิน 63 เพราะเก็บใน 6 บิต)
TARGET_DF_MAX = 100          # ความถี่ของจุดคู่ห่างจากจุดยึดได้ไม่เกินกี่ช่อง (100 × 7.8 ≈ 780 Hz)

# ---------------------------------------------------------------------
# 5) การตัดสินผล
# ---------------------------------------------------------------------
# ตอบว่า "เจอเพลง" ก็ต่อเมื่อผ่านทั้ง 2 เงื่อนไข
MIN_MATCHES = 12             # 1) จำนวน hash ที่ offset ตรงกัน ต้องไม่น้อยกว่านี้
MIN_RATIO = 2.5              # 2) คะแนนอันดับ 1 ต้องมากกว่าคะแนน "คู่แข่ง" อย่างน้อยกี่เท่า
                             #    (เพลงที่ไม่มีในฐานข้อมูลมักได้ ratio ≈ 1–1.6)
